#!/usr/bin/env node
/**
 * Provisions the local provider's accounts from the environment.
 *
 * `init` writes infra/compose/.env, generating a random password for every account that does not
 * have one yet. `provision` sets those passwords on the users the imported realm defines, through
 * the provider's own admin API, and restores the one-time-password enrolment each console user
 * must complete before the provider issues a session.
 *
 * No password is committed, printed, or embedded: values live only in the ignored .env file and
 * in the provider's credential store (NFR-023, NFR-029). Specification anchors: FEAT-009, NFR-029.
 *
 * Usage:
 *   node infra/compose/bootstrap-oidc.mjs init        # create or refresh infra/compose/.env
 *   docker compose -f infra/compose/compose.yaml up -d
 *   node infra/compose/bootstrap-oidc.mjs provision   # set the passwords on the realm users
 */

import { randomBytes } from 'node:crypto';
import { chmodSync, existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const COMPOSE_DIR = dirname(fileURLToPath(import.meta.url));
const ENV_PATH = join(COMPOSE_DIR, '.env');
const REALM = 'aegis';

/** Non-secret local settings. They describe the provider, not a credential. */
const LOCAL_SETTINGS = {
  AEGIS_OIDC_PUBLIC_URL: 'http://localhost:8081',
  AEGIS_OIDC_PUBLIC_PORT: '8081',
  AEGIS_OIDC_ISSUER: 'http://localhost:8081/realms/aegis',
  AEGIS_OIDC_CONSOLE_CLIENT_ID: 'aegis-console',
  AEGIS_OIDC_CONSOLE_REDIRECT_URI: 'http://localhost:3000/',
  AEGIS_OIDC_AUDIENCE: 'aegis-gateway',
  AEGIS_GATEWAY_PORT: '8443',
  KEYCLOAK_ADMIN_USERNAME: 'admin',
  KEYCLOAK_LOG_LEVEL: 'warn',
};

/** Accounts the realm defines, and the variable each password comes from. */
const ACCOUNTS = [
  { role: 'admin', username: 'aegis-admin', variable: 'AEGIS_OIDC_ADMIN_USER_PASSWORD' },
  { role: 'operator', username: 'aegis-operator', variable: 'AEGIS_OIDC_OPERATOR_USER_PASSWORD' },
  { role: 'auditor', username: 'aegis-auditor', variable: 'AEGIS_OIDC_AUDITOR_USER_PASSWORD' },
  { role: 'viewer', username: 'aegis-viewer', variable: 'AEGIS_OIDC_VIEWER_USER_PASSWORD' },
];

/** Every variable whose value is a credential. */
const SECRET_VARIABLES = ['KEYCLOAK_ADMIN_PASSWORD', ...ACCOUNTS.map((account) => account.variable)];

const ENV_HEADER = [
  '# Local credentials for the identity stack. Generated by bootstrap-oidc.mjs init and',
  '# ignored by git: it holds the passwords compose requires and the smoke check signs in with.',
  '# Regenerate a value only by editing or deleting the line and running init again.',
  '',
];

function readEnvFile() {
  if (!existsSync(ENV_PATH)) return new Map();
  const entries = new Map();
  for (const line of readFileSync(ENV_PATH, 'utf8').split(/\r?\n/)) {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith('#')) continue;
    const separator = trimmed.indexOf('=');
    if (separator <= 0) continue;
    entries.set(trimmed.slice(0, separator).trim(), trimmed.slice(separator + 1).trim());
  }
  return entries;
}

function writeEnvFile(entries) {
  const lines = [...ENV_HEADER];
  for (const key of [...Object.keys(LOCAL_SETTINGS), ...SECRET_VARIABLES]) {
    lines.push(`${key}=${entries.get(key) ?? ''}`);
  }
  lines.push('');
  writeFileSync(ENV_PATH, lines.join('\n'), { encoding: 'utf8', mode: 0o600 });
  try {
    chmodSync(ENV_PATH, 0o600);
  } catch {
    // A filesystem without POSIX modes still gets the file; compose reads it either way.
  }
}

function randomPassword() {
  // 32 characters of base64url: strong enough for a workstation provider, and free of characters
  // a shell, URL, or compose variable would need to escape.
  return randomBytes(24).toString('base64url');
}

function init() {
  const entries = readEnvFile();
  const generated = [];
  for (const [key, value] of Object.entries(LOCAL_SETTINGS)) {
    if (!entries.get(key)) entries.set(key, process.env[key] || value);
  }
  for (const key of SECRET_VARIABLES) {
    if (!entries.get(key)) {
      entries.set(key, process.env[key] || randomPassword());
      generated.push(key);
    }
  }
  writeEnvFile(entries);
  console.log(`bootstrap: wrote ${ENV_PATH}`);
  if (generated.length) {
    console.log(`bootstrap: generated a random value for ${generated.join(', ')}`);
  } else {
    console.log('bootstrap: every credential already present, nothing regenerated');
  }
  for (const account of ACCOUNTS) {
    console.log(`bootstrap: ${account.username} password is ${account.variable} in .env`);
  }
  console.log('bootstrap: next, start the stack and run provision');
}

function loadCredentials() {
  if (!existsSync(ENV_PATH)) {
    throw new Error('infra/compose/.env is missing; run: node infra/compose/bootstrap-oidc.mjs init');
  }
  const entries = readEnvFile();
  const missing = [];
  const secrets = {};
  for (const key of SECRET_VARIABLES) {
    const value = entries.get(key) || process.env[key];
    if (!value) missing.push(key);
    secrets[key] = value;
  }
  if (missing.length) {
    throw new Error(
      `no value for ${missing.join(', ')} in infra/compose/.env; run init to generate one`
    );
  }
  const settings = {};
  for (const [key, fallback] of Object.entries(LOCAL_SETTINGS)) {
    settings[key] = entries.get(key) || process.env[key] || fallback;
  }
  return { settings, secrets };
}

async function request(url, options = {}) {
  const response = await fetch(url, options);
  const text = await response.text();
  if (!response.ok) {
    throw new Error(`${options.method ?? 'GET'} ${url} answered HTTP ${response.status}: ${text.slice(0, 200)}`);
  }
  return text ? JSON.parse(text) : null;
}

async function adminToken(settings, secrets) {
  const body = new URLSearchParams({
    grant_type: 'password',
    client_id: 'admin-cli',
    username: settings.KEYCLOAK_ADMIN_USERNAME,
    password: secrets.KEYCLOAK_ADMIN_PASSWORD,
  });
  const token = await request(
    `${settings.AEGIS_OIDC_PUBLIC_URL}/realms/master/protocol/openid-connect/token`,
    {
      method: 'POST',
      headers: { 'Content-Type': 'application/x-www-form-urlencoded' },
      body,
    }
  );
  return token.access_token;
}

function adminHeaders(token) {
  return { Authorization: `Bearer ${token}`, 'Content-Type': 'application/json', Accept: 'application/json' };
}

async function findUser(settings, token, username) {
  const url =
    `${settings.AEGIS_OIDC_PUBLIC_URL}/admin/realms/${REALM}/users` +
    `?exact=true&username=${encodeURIComponent(username)}`;
  const found = await request(url, { headers: adminHeaders(token) });
  return found?.[0] ?? null;
}

async function provisionAccount(settings, token, account, password) {
  const user = await findUser(settings, token, account.username);
  if (!user) {
    throw new Error(
      `the provider has no user ${account.username}; start the stack so the realm import runs`
    );
  }
  const base = `${settings.AEGIS_OIDC_PUBLIC_URL}/admin/realms/${REALM}/users/${user.id}`;
  await request(`${base}/reset-password`, {
    method: 'PUT',
    headers: adminHeaders(token),
    body: JSON.stringify({ type: 'password', value: password, temporary: false }),
  });
  // A console session never exists before the second factor is enrolled (NFR-029).
  const current = await request(base, { headers: adminHeaders(token) });
  const requiredActions = new Set(current.requiredActions ?? []);
  requiredActions.add('CONFIGURE_TOTP');
  await request(base, {
    method: 'PUT',
    headers: adminHeaders(token),
    body: JSON.stringify({ requiredActions: [...requiredActions] }),
  });
}

async function provision() {
  const { settings, secrets } = loadCredentials();
  const token = await adminToken(settings, secrets);
  for (const account of ACCOUNTS) {
    await provisionAccount(settings, token, account, secrets[account.variable]);
    console.log(`bootstrap: ${account.username} password set, enrolment required on first sign-in`);
  }
  console.log('bootstrap: every console account is provisioned');
}

const command = process.argv[2];
try {
  if (command === 'init') {
    init();
  } else if (command === 'provision') {
    await provision();
  } else {
    console.error('usage: bootstrap-oidc.mjs <init|provision>');
    process.exitCode = 2;
  }
} catch (error) {
  console.error(`bootstrap: FAILED: ${error.message}`);
  process.exitCode = 1;
}
